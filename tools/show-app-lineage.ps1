#Requires -Version 5.1
<#
.SYNOPSIS
  รายงานต้นทางของ App versions (lineage) — HTML + mermaid + ตาราง

.DESCRIPTION
  อ่าน versions\*\.aptstack-source และ .aptstack-version
  แล้วสร้างรายงานในโฟลเดอร์ report_html (ค่าเริ่ม):
    - app-lineage.html   หน้าอธิบายต้นทาง + ไดอะแกรม
    - app-lineage.mmd    mermaid source
    - app-lineage.csv    ตารางดิบ

.EXAMPLE
  .\tools\show-app-lineage.ps1
  .\tools\show-app-lineage.ps1 -Out .\dist\report_html
  .\tools\show-app-lineage.ps1 -Help
#>
[CmdletBinding()]
param(
    [string]$VersionsDir = '',
    # ค่าเริ่ม = <root>\report_html
    [string]$Out = '',
    [Alias('h','?','Help')]
    [switch]$HelpFlag
)

function Show-Usage {
    Write-Host ''
    Write-Host '  show-app-lineage — รายงานต้นทางของ app versions เป็น HTML' -ForegroundColor Cyan
    Write-Host ''
    Write-Host 'วิธีใช้:'
    Write-Host '  .\tools\show-app-lineage.ps1'
    Write-Host '  .\tools\show-app-lineage.ps1 -Out .\dist\report_html'
    Write-Host '  .\tools\show-app-lineage.ps1 -Help'
    Write-Host ''
    Write-Host 'ค่าเริ่ม output: <bundle>\report_html\'
    Write-Host '  app-lineage.html  — เปิดในเบราว์เซอร์ (mermaid + ตาราง)'
    Write-Host '  app-lineage.mmd   — โค้ดไดอะแกรม'
    Write-Host '  app-lineage.csv   — ตารางดิบ'
    Write-Host ''
    Write-Host 'ใช้คู่ deploy diff:'
    Write-Host '  .\tools\make-deploy-diff.ps1 -Base <source ด้านบน> -Compare .\versions\<app>'
    Write-Host ''
}

if ($HelpFlag) { Show-Usage; exit 0 }

$ErrorActionPreference = 'Stop'
$scriptDir = Split-Path -Parent $MyInvocation.MyCommand.Path
$root = Split-Path -Parent $scriptDir
if (-not $VersionsDir) { $VersionsDir = Join-Path $root 'versions' }
if (-not (Test-Path $VersionsDir)) { throw "ไม่พบ versions: $VersionsDir" }
if (-not $Out) { $Out = Join-Path $root 'report_html' }

function Get-Kv([string]$path) {
    $h = @{}
    if (-not (Test-Path $path)) { return $h }
    foreach ($l in (Get-Content $path -ErrorAction SilentlyContinue)) {
        if ("$l" -match '^\s*#' -or "$l" -notmatch '=') { continue }
        $i = "$l".IndexOf('=')
        if ($i -gt 0) { $h[$l.Substring(0, $i).Trim()] = $l.Substring($i + 1).Trim() }
    }
    return $h
}

function HtmlEnc([string]$s) {
    if ($null -eq $s) { return '' }
    return [Net.WebUtility]::HtmlEncode($s)
}

# active app from stack.json
$activeApp = ''
try {
    $sj = Get-Kv (Join-Path $root 'config\stack.json')
    # stack.json is JSON not kv — read properly
    $j = Get-Content (Join-Path $root 'config\stack.json') -Raw -Encoding UTF8 | ConvertFrom-Json
    $activeApp = "$($j.app)"
} catch { }

$apps = @()
foreach ($d in Get-ChildItem $VersionsDir -Directory | Sort-Object Name) {
    $srcH = Get-Kv (Join-Path $d.FullName '.aptstack-source')
    $verH = Get-Kv (Join-Path $d.FullName '.aptstack-version')
    $apps += [pscustomobject]@{
        App       = $d.Name
        IsActive  = ($d.Name -ieq $activeApp)
        Family    = $verH['family']
        Version   = $verH['version']
        Kind      = $srcH['kind']
        Source    = $srcH['source']
        Installed = $srcH['installed']
        Path      = $d.FullName
        SourceExists = if ($srcH['source']) { [bool](Test-Path $srcH['source']) } else { $false }
    }
}

# ---- mermaid ----
$mmLines = [System.Collections.Generic.List[string]]::new()
$mmLines.Add('flowchart LR')
$mmLines.Add('  %% generated by tools/show-app-lineage.ps1')
$mmLines.Add("  %% $(Get-Date -Format 'yyyy-MM-dd HH:mm')")

# group by source path
$bySource = $apps | Group-Object { if ($_.Source) { $_.Source } else { '(no source)' } }
$n = 0
foreach ($g in $bySource) {
    $n++
    $srcId = "S$n"
    $srcName = Split-Path $g.Name -Leaf
    if ([string]::IsNullOrWhiteSpace($srcName)) { $srcName = $g.Name }
    $exists = $g.Group[0].SourceExists
    $cls = if ($exists) { ':::ok' } else { ':::miss' }
    $safeSrc = (HtmlEnc $srcName) -replace '"', "'"
    $mmLines.Add('  ' + $srcId + '["' + $safeSrc + '"] ' + $cls)
    foreach ($a in $g.Group) {
        $aid = 'A_' + ($a.App -replace '[^A-Za-z0-9_]', '_')
        $safeApp = (HtmlEnc $a.App) -replace '"', "'"
        $mmLines.Add('  ' + $aid + '["' + $safeApp + '"]')
        $mmLines.Add('  ' + $srcId + ' --> ' + $aid)
    }
}
$mmLines.Add('  classDef ok fill:#e8f5e9,stroke:#2e7d32')
$mmLines.Add('  classDef miss fill:#ffebee,stroke:#c62828')
$mermaid = $mmLines -join "`n"

# ---- output ----
$outDir = [IO.Path]::GetFullPath($Out)
New-Item -ItemType Directory -Path $outDir -Force | Out-Null

$csvPath = Join-Path $outDir 'app-lineage.csv'
$mmdPath = Join-Path $outDir 'app-lineage.mmd'
$htmlPath = Join-Path $outDir 'app-lineage.html'
$indexPath = Join-Path $outDir 'index.html'

$apps | Select-Object App, IsActive, Family, Version, Kind, Source, SourceExists, Installed, Path |
    Export-Csv -Path $csvPath -NoTypeInformation -Encoding UTF8
Set-Content -Path $mmdPath -Value $mermaid -Encoding UTF8

# table rows
$rowsHtml = ''
foreach ($a in $apps) {
    $badge = if ($a.IsActive) { ' <span class="badge active">ACTIVE</span>' } else { '' }
    $srcOk = if ($a.SourceExists) {
        '<span class="badge ok">มีไฟล์ต้นทาง</span>'
    } elseif ($a.Source) {
        '<span class="badge miss">ไม่พบ path</span>'
    } else {
        '<span class="badge warn">ไม่มี meta</span>'
    }
    $diffCmd = ''
    if ($a.Source -and $a.SourceExists) {
        $rel = $a.Source -replace "'", "''"
        $verRel = ".\versions\$($a.App)" -replace "'", "''"
        $diffCmd = "<code class='cmd'>.\tools\make-deploy-diff.ps1 -Base '$rel' -Compare '$verRel'</code>"
    }
    $rowsHtml += @"
<tr>
  <td><strong>$((HtmlEnc $a.App))</strong>$badge</td>
  <td>$(HtmlEnc $a.Family)</td>
  <td>$(HtmlEnc $a.Kind)</td>
  <td class="src">$(HtmlEnc $a.Source)<br>$srcOk</td>
  <td>$(HtmlEnc $a.Installed)</td>
  <td class="cmdcell">$diffCmd</td>
</tr>
"@
}

